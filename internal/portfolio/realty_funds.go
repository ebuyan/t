// HoldingLabel — подпись строки состава: тикер и название. Фонд из realtyFunds
// подписан коротким именем вместо кода (код пая обычно равен ISIN и ничего не
// говорит), остальные — тикером и названием из справки или от брокера.
func HoldingLabel(h *Holding, m *Meta) (ticker, name string) {
	if short, ok := realtyFunds[h.Ticker]; ok {
		return short, ""
	}
	if m != nil {
		if n := m.Names[h.Ticker]; n != "" {
			return h.Ticker, n
		}
	}
	return h.Ticker, h.Name
}
